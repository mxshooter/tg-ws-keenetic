"""Fake TLS handshake (ee-secret) — used to disguise MTProto as HTTPS.

This is the proxy server side: we accept a TLS ClientHello, verify it was
generated by a Telegram client that knows our secret, reply with a forged
ServerHello, then expose a tiny stream wrapper that strips TLS record
framing from application data.

The forged ServerHello mirrors what the client offered (cipher suite,
post-quantum key share) and the dummy ApplicationData record matches the
size of the masking site's first encrypted record, so the flight does not
stand out to traffic fingerprinting (upstream tg-ws-proxy #1473).
"""
from __future__ import annotations

import asyncio
import hmac
import hashlib
import logging
import os
import random
import ssl
import struct
import time
from typing import Dict, FrozenSet, NamedTuple, Optional, Tuple

from .constants import (
    APPDATA_MIN,
    CIPHER_PREFERENCE,
    CLIENT_RANDOM_LEN,
    CLIENT_RANDOM_OFFSET,
    EXT_KEY_SHARE,
    EXT_SUPPORTED_VERSIONS,
    FALLBACK_APPDATA_RANGE,
    GROUP_X25519,
    GROUP_X25519MLKEM768,
    MLKEM768_CIPHERTEXT_LEN,
    PROFILE_PROBE_TIMEOUT,
    SERVER_HELLO_DELAY,
    SESSION_ID_LEN,
    SESSION_ID_OFFSET,
    TIMESTAMP_TOLERANCE,
    TLS_APPDATA_MAX,
    TLS_RECORD_APPDATA,
    TLS_RECORD_CCS,
    TLS_RECORD_HANDSHAKE,
    TLS_VERSION_12,
    X25519MLKEM768_CLIENT_SHARE_LEN,
    X25519_KEY_LEN,
)
from .websocket import set_x25519

try:
    # Entware routers rarely ship cryptography: generating a real X25519 key
    # is optional, the random fallback below is good enough for a reply the
    # client never uses to derive keys (the real crypto is the ee-secret HMAC).
    from cryptography.hazmat.primitives.asymmetric.x25519 import (
        X25519PrivateKey,
    )
except ImportError:
    X25519PrivateKey = None

X25519_BACKEND = "cryptography"


def x25519_backend() -> str:
    """Name (and version) of the implementation behind the forged key share."""
    if X25519PrivateKey is None:
        return "random-fallback"
    try:
        from cryptography import __version__ as version
    except ImportError:
        return X25519_BACKEND
    return "%s %s" % (X25519_BACKEND, version)


def has_real_x25519() -> bool:
    """False when key shares are random bytes instead of Curve25519 points."""
    return X25519PrivateKey is not None

log = logging.getLogger("tgwsproxy.fake_tls")

_CCS_FRAME = b"\x14\x03\x03\x00\x01\x01"

_SH_RANDOM_OFFSET = 11

# Size of the first encrypted record the masking site sends after
# ServerHello; set once at startup by probe_appdata_len().
_profiled_appdata_len: Optional[int] = None


class ClientHelloInfo(NamedTuple):
    """What the forged ServerHello needs to mirror from the ClientHello."""

    cipher_suites: FrozenSet[int]
    key_shares: Dict[int, int]  # named group -> key_exchange length


_EMPTY_HELLO_INFO = ClientHelloInfo(frozenset(), {})


def verify_client_hello(
    data: bytes, secret: bytes
) -> Optional[Tuple[bytes, bytes, int]]:
    """Return (client_random, session_id, timestamp) if HELLO is authentic."""
    if len(data) < 43:
        return None
    if data[0] != TLS_RECORD_HANDSHAKE or data[5] != 0x01:
        return None

    client_random = bytes(
        data[CLIENT_RANDOM_OFFSET : CLIENT_RANDOM_OFFSET + CLIENT_RANDOM_LEN]
    )

    zeroed = bytearray(data)
    zeroed[
        CLIENT_RANDOM_OFFSET : CLIENT_RANDOM_OFFSET + CLIENT_RANDOM_LEN
    ] = b"\x00" * CLIENT_RANDOM_LEN

    expected = hmac.new(secret, bytes(zeroed), hashlib.sha256).digest()
    if not hmac.compare_digest(expected[:28], client_random[:28]):
        return None

    ts_xor = bytes(client_random[28 + i] ^ expected[28 + i] for i in range(4))
    timestamp = struct.unpack("<I", ts_xor)[0]
    if abs(int(time.time()) - timestamp) > TIMESTAMP_TOLERANCE:
        return None

    session_id = b"\x00" * SESSION_ID_LEN
    if (
        len(data) >= SESSION_ID_OFFSET + SESSION_ID_LEN
        and data[43] == SESSION_ID_LEN
    ):
        session_id = bytes(
            data[SESSION_ID_OFFSET : SESSION_ID_OFFSET + SESSION_ID_LEN]
        )

    return client_random, session_id, timestamp


def parse_client_hello(data: bytes) -> ClientHelloInfo:
    """Extract offered cipher suites and key_share groups from a ClientHello.

    Returns empty info on malformed input so the caller falls back to the
    plain X25519 / TLS_AES_128_GCM_SHA256 answer.
    """
    try:
        pos = 5 + 4 + 2 + CLIENT_RANDOM_LEN
        pos += 1 + data[pos]

        suites_len = struct.unpack_from(">H", data, pos)[0]
        pos += 2
        suites_end = pos + suites_len
        if suites_end > len(data):
            return _EMPTY_HELLO_INFO
        suites = frozenset(
            struct.unpack_from(">H", data, off)[0]
            for off in range(pos, suites_end - 1, 2)
        )
        pos = suites_end

        pos += 1 + data[pos]

        ext_total = struct.unpack_from(">H", data, pos)[0]
        pos += 2
        ext_end = min(pos + ext_total, len(data))
        key_shares: Dict[int, int] = {}
        while pos + 4 <= ext_end:
            ext_type, ext_len = struct.unpack_from(">HH", data, pos)
            pos += 4
            if ext_type == EXT_KEY_SHARE and pos + 2 <= ext_end:
                shares_end = min(
                    pos + 2 + struct.unpack_from(">H", data, pos)[0], ext_end
                )
                off = pos + 2
                while off + 4 <= shares_end:
                    group, key_len = struct.unpack_from(">HH", data, off)
                    off += 4 + key_len
                    if off <= shares_end:
                        key_shares.setdefault(group, key_len)
            pos += ext_len
    except (IndexError, struct.error):
        return _EMPTY_HELLO_INFO

    return ClientHelloInfo(suites, key_shares)


def _select_cipher_suite(info: ClientHelloInfo) -> int:
    for suite in CIPHER_PREFERENCE:
        if suite in info.cipher_suites:
            return suite
    return CIPHER_PREFERENCE[0]


def _x25519_public_key() -> bytes:
    if X25519PrivateKey is not None:
        try:
            return X25519PrivateKey.generate().public_key().public_bytes_raw()
        except AttributeError:  # cryptography < 40
            pass
    # Real public keys are field elements below 2^255: keep the top bit clear.
    key = bytearray(os.urandom(X25519_KEY_LEN))
    key[-1] &= 0x7F
    return bytes(key)


def _server_key_share(info: ClientHelloInfo) -> Tuple[int, bytes]:
    # Mirror the hybrid post-quantum group when the client offers it, as
    # current browsers and servers do; the client never derives keys from it.
    if (
        info.key_shares.get(GROUP_X25519MLKEM768)
        == X25519MLKEM768_CLIENT_SHARE_LEN
    ):
        return (
            GROUP_X25519MLKEM768,
            os.urandom(MLKEM768_CIPHERTEXT_LEN) + _x25519_public_key(),
        )
    return GROUP_X25519, _x25519_public_key()


def _appdata_len() -> int:
    if _profiled_appdata_len is not None:
        return _profiled_appdata_len
    return random.randint(*FALLBACK_APPDATA_RANGE)


def build_server_hello(
    secret: bytes,
    client_random: bytes,
    session_id: bytes,
    info: ClientHelloInfo = _EMPTY_HELLO_INFO,
) -> bytes:
    """Forge a ServerHello + dummy AppData that matches the client's HMAC.

    ``info`` comes from :func:`parse_client_hello`: the answer mirrors the
    cipher suite and key share the client offered. Telegram clients parse
    exactly these three records (ServerHello, CCS, ApplicationData) and check
    the HMAC over all of them, so the shape is fixed while sizes may vary.
    """
    group, key_exchange = _server_key_share(info)
    extensions = (
        struct.pack(">HHH", EXT_SUPPORTED_VERSIONS, 2, 0x0304)
        + struct.pack(
            ">HHHH",
            EXT_KEY_SHARE,
            4 + len(key_exchange),
            group,
            len(key_exchange),
        )
        + key_exchange
    )

    body = (
        TLS_VERSION_12
        + b"\x00" * 32  # server_random — filled in later
        + bytes([len(session_id)])
        + session_id
        + struct.pack(">H", _select_cipher_suite(info))
        + b"\x00"
        + struct.pack(">H", len(extensions))
        + extensions
    )
    message = b"\x02" + struct.pack(">I", len(body))[1:] + body
    server_hello = (
        bytes([TLS_RECORD_HANDSHAKE])
        + TLS_VERSION_12
        + struct.pack(">H", len(message))
        + message
    )

    appdata_len = _appdata_len()
    app_record = (
        bytes([TLS_RECORD_APPDATA])
        + TLS_VERSION_12
        + struct.pack(">H", appdata_len)
        + os.urandom(appdata_len)
    )

    response = server_hello + _CCS_FRAME + app_record

    server_random = hmac.new(
        secret, client_random + response, hashlib.sha256
    ).digest()
    final = bytearray(response)
    final[_SH_RANDOM_OFFSET : _SH_RANDOM_OFFSET + 32] = server_random
    return bytes(final)


def set_profiled_appdata_len(length: Optional[int]) -> None:
    """Set (or clear) the ApplicationData size copied from the masking site."""
    global _profiled_appdata_len
    if length is None:
        _profiled_appdata_len = None
    else:
        _profiled_appdata_len = max(APPDATA_MIN, min(length, TLS_APPDATA_MAX))


def first_appdata_record_len(data: bytes) -> Optional[int]:
    """Length of the first ApplicationData record in a server's first flight.

    Returns None while more data is needed, 0 if the flight cannot contain
    one (alert, TLS 1.2 handshake, garbage).
    """
    pos = 0
    while pos + 5 <= len(data):
        rec_type = data[pos]
        rec_len = struct.unpack_from(">H", data, pos + 3)[0]
        if rec_type == TLS_RECORD_APPDATA:
            return rec_len
        if rec_type not in (TLS_RECORD_HANDSHAKE, TLS_RECORD_CCS):
            return 0
        pos += 5 + rec_len
    return None


async def probe_appdata_len(
    domain: str, port: int = 443, timeout: float = PROFILE_PROBE_TIMEOUT
) -> Optional[int]:
    """Measure the first encrypted record the masking site sends.

    Only the raw first flight is read; the TLS handshake is never completed.
    Returns None when the site cannot be profiled.
    """
    if not getattr(ssl, "HAS_TLSv1_3", False):
        log.warning(
            "Fake TLS profile: local ssl lacks TLS 1.3, using random "
            "record sizes"
        )
        return None

    writer = None
    try:
        ctx = ssl.create_default_context()
        set_x25519(ctx)
        ctx.check_hostname = False
        ctx.verify_mode = ssl.CERT_NONE
        ctx.minimum_version = ssl.TLSVersion.TLSv1_3
        ctx.set_alpn_protocols(["h2", "http/1.1"])
        outgoing = ssl.MemoryBIO()
        tls = ctx.wrap_bio(ssl.MemoryBIO(), outgoing, server_hostname=domain)
        try:
            tls.do_handshake()
        except ssl.SSLWantReadError:
            pass
        client_hello = outgoing.read()

        # Share one deadline across connecting, sending and reading the flight.
        loop = asyncio.get_running_loop()
        deadline = loop.time() + timeout
        reader, writer = await asyncio.wait_for(
            asyncio.open_connection(domain, port), timeout=timeout
        )
        writer.write(client_hello)
        await asyncio.wait_for(writer.drain(), timeout=deadline - loop.time())

        flight = bytearray()
        while True:
            remaining = deadline - loop.time()
            if remaining <= 0:
                raise asyncio.TimeoutError
            chunk = await asyncio.wait_for(
                reader.read(16384), timeout=remaining
            )
            if not chunk:
                return None
            flight.extend(chunk)
            length = first_appdata_record_len(bytes(flight))
            if length is not None:
                return length or None
    except Exception as exc:
        log.warning(
            "Fake TLS profile: cannot probe %s:%d: %r", domain, port, exc
        )
        return None
    finally:
        if writer is not None:
            writer.close()


def wrap_tls_records(data: bytes) -> bytes:
    """Chop a buffer into TLS Application Data records of <=16KB each."""
    parts = []
    for offset in range(0, len(data), TLS_APPDATA_MAX):
        chunk = data[offset : offset + TLS_APPDATA_MAX]
        parts.append(b"\x17\x03\x03" + struct.pack(">H", len(chunk)) + chunk)
    return b"".join(parts)


class FakeTlsStream:
    """Stream-like wrapper that hides TLS record framing.

    Reads strip TLS app-data record headers; writes wrap data into records.
    """

    __slots__ = ("_reader", "_writer", "_pending", "_record_left")

    def __init__(
        self, reader: asyncio.StreamReader, writer: asyncio.StreamWriter
    ):
        self._reader = reader
        self._writer = writer
        self._pending = bytearray()
        self._record_left = 0

    async def readexactly(self, n: int) -> bytes:
        while len(self._pending) < n:
            chunk = await self._read_record_chunk()
            if not chunk:
                raise asyncio.IncompleteReadError(bytes(self._pending), n)
            self._pending.extend(chunk)
        out = bytes(self._pending[:n])
        del self._pending[:n]
        return out

    async def read(self, n: int) -> bytes:
        if self._pending:
            out = bytes(self._pending[:n])
            del self._pending[:n]
            return out
        chunk = await self._read_record_chunk()
        if not chunk:
            return b""
        if len(chunk) > n:
            self._pending.extend(chunk[n:])
            return chunk[:n]
        return chunk

    async def _read_record_chunk(self) -> bytes:
        """Return at most one record's worth of bytes; handles fragments."""
        if self._record_left > 0:
            chunk = await self._reader.read(self._record_left)
            if not chunk:
                return b""
            self._record_left -= len(chunk)
            return chunk

        while True:
            header = await self._reader.readexactly(5)
            rec_type = header[0]
            rec_len = struct.unpack(">H", header[3:5])[0]

            if rec_type == TLS_RECORD_CCS:
                if rec_len > 0:
                    await self._reader.readexactly(rec_len)
                continue

            if rec_type != TLS_RECORD_APPDATA:
                return b""

            chunk = await self._reader.read(min(rec_len, 65536))
            if not chunk:
                return b""
            remaining = rec_len - len(chunk)
            if remaining > 0:
                self._record_left = remaining
            return chunk

    def write(self, data: bytes) -> None:
        self._writer.write(wrap_tls_records(data))

    async def drain(self) -> None:
        await self._writer.drain()

    def close(self) -> None:
        self._writer.close()

    async def wait_closed(self) -> None:
        await self._writer.wait_closed()

    def get_extra_info(self, name, default=None):
        return self._writer.get_extra_info(name, default)

    @property
    def transport(self):
        return self._writer.transport

    def is_closing(self):
        return self._writer.is_closing()


async def relay_to_masking_domain(
    reader: asyncio.StreamReader,
    writer: asyncio.StreamWriter,
    initial: bytes,
    domain: str,
    label: str,
) -> None:
    """Tunnel the client to a real HTTPS site when Fake-TLS auth fails."""
    try:
        upstream_reader, upstream_writer = await asyncio.wait_for(
            asyncio.open_connection(domain, 443), timeout=10
        )
    except Exception as exc:
        log.warning("[%s] masking: cannot reach %s: %s", label, domain, exc)
        return

    log.debug("[%s] masking -> %s:443", label, domain)
    try:
        if initial:
            upstream_writer.write(initial)
            await upstream_writer.drain()

        async def pipe(src, dst):
            try:
                while True:
                    chunk = await src.read(16384)
                    if not chunk:
                        break
                    dst.write(chunk)
                    await dst.drain()
            except (ConnectionError, OSError, asyncio.CancelledError):
                pass
            finally:
                try:
                    dst.close()
                    await dst.wait_closed()
                except Exception:
                    pass

        await asyncio.gather(
            pipe(reader, upstream_writer), pipe(upstream_reader, writer)
        )
    finally:
        try:
            upstream_writer.close()
        except Exception:
            pass
